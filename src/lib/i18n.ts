export function formatDA(amount: number, lang: Language = 'fr'): string {
  if (lang === 'ar') {
    return `${amount.toLocaleString('ar-DZ')} د.ج`;
  }
  return `${amount.toLocaleString('fr-FR')} DA`;
}

export function buildWhatsAppLink(phone: string, text: string): string {
  // Algerian boutique phone or customer phone
  const cleanPhone = phone.replace(/[^0-9]/g, '');
  const finalPhone = cleanPhone.startsWith('0') ? `213${cleanPhone.slice(1)}` : cleanPhone;
  return `https://wa.me/${finalPhone}?text=${encodeURIComponent(text)}`;
}

